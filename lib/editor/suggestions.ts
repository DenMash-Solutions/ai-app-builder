/**
 * Datalist suggestions for className: every class used anywhere in the
 * current spec (deduped) merged with the curated Tailwind set, sorted.
 * A null/undefined spec still yields the curated base.
 */
export function getClassSuggestions(spec: Spec | null | undefined): string[] {
  const tokens = new Set<string>(COMMON_TAILWIND_CLASSES);
  const elements = spec?.elements;
  if (elements) {
    for (const element of Object.values(elements)) {
      for (const token of toClassTokens(element.props?.className)) {
        tokens.add(token);
      }
    }
  }
  return [...tokens].sort((a, b) => a.localeCompare(b));
}
